select
    item_id,
    nullif(trim(name), '')          as name,
    -- Stub rows (Item only, no ItemSparse) carry class and slot but no name, level or stats.
    name is not null                as has_details,
    quality,
    item_level,
    required_level,
    item_class                      as item_class_id,
    item_subclass                   as item_subclass_id,
    inventory_type,
    binding,
    stackable                       as max_stack,
    stats,
    stat_budget,
    armor,
    armor_source,
    damage,
    spells,
    allowable_class_mask,
    allowable_race_mask,
    required_skill                  as required_skill_id,
    required_skill_rank,
    sell_price                      as sell_price_copper,
    buy_price                       as buy_price_copper,
    set_id                          as item_set_id,
    icon_file_data_id,
    description,
    source.kind                     as source_kind,
    source.ref                      as source_ref,
    build_first_seen,
    build_last_seen,
    confidence
from {{ source('opendata', 'items') }}
