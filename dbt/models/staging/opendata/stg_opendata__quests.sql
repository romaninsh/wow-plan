select
    quest_id,
    name,
    quest_level,
    min_level,
    type                            as quest_info_id,
    flags,
    race_mask,
    zone_or_sort,
    next_quest_id,
    objectives,
    description,
    objective_items,
    objective_npcs,
    rewards.xp                      as reward_xp,
    rewards.xp_multiplier           as reward_xp_multiplier,
    rewards.money                   as reward_money_copper,
    rewards.items                   as reward_items,
    rewards.choice_items            as reward_choice_items,
    rewards.reputation              as reward_reputation,
    source.kind                     as source_kind,
    source.ref                      as source_ref,
    build_first_seen,
    build_last_seen,
    confidence
from {{ source('opendata', 'quests') }}
